use base64::{engine::general_purpose::URL_SAFE_NO_PAD, Engine};
use hmac::{Hmac, Mac};
use serde::Deserialize;
use sha2::Sha256;

type HmacSha256 = Hmac<Sha256>;

// Token: base64url(json claims) + "." + hex(hmac_sha256(secret, base64url payload)).
// Laravel issues the same format (ProctorService::token).
#[derive(Deserialize, Debug, PartialEq)]
pub struct Claims {
    pub sub: i64,
    pub exp: u64,
    #[serde(default)]
    pub att: Option<i64>,
    #[serde(default)]
    pub asm: Vec<i64>,
    #[serde(default)]
    pub ass: Option<i64>,
    #[serde(default)]
    pub sch: Option<i64>,
}

#[derive(Debug, PartialEq)]
pub enum TokenError {
    Malformed,
    BadSignature,
    Expired,
}

pub struct Secret(Vec<u8>);

impl Secret {
    pub fn new(key: &str) -> Option<Self> {
        (key.len() >= 32).then(|| Self(key.as_bytes().to_vec()))
    }

    pub fn verify(&self, token: &str, now: u64) -> Result<Claims, TokenError> {
        let (payload, sig_hex) = token.split_once('.').ok_or(TokenError::Malformed)?;
        let sig = hex::decode(sig_hex).map_err(|_| TokenError::Malformed)?;

        let mut mac = HmacSha256::new_from_slice(&self.0).map_err(|_| TokenError::Malformed)?;
        mac.update(payload.as_bytes());
        mac.verify_slice(&sig).map_err(|_| TokenError::BadSignature)?;

        let json = URL_SAFE_NO_PAD.decode(payload).map_err(|_| TokenError::Malformed)?;
        let claims: Claims = serde_json::from_slice(&json).map_err(|_| TokenError::Malformed)?;
        if claims.exp <= now {
            return Err(TokenError::Expired);
        }
        Ok(claims)
    }
}

impl Claims {
    /// A student sees only their own attempt, their own entry decision (user id), and
    /// exam-wide control events (pause/resume/stop) of their own exam. A teacher sees everything of their school.
    pub fn covers(&self, attempt_id: Option<i64>, assessment_id: Option<i64>, user_id: Option<i64>, school_id: Option<i64>, students_only: bool) -> bool {
        attempt_id.is_some_and(|a| Some(a) == self.att)
            || assessment_id.is_some_and(|s| self.asm.contains(&s))
            || user_id.is_some_and(|u| u == self.sub)
            || (students_only && assessment_id.is_some() && assessment_id == self.ass)
            || school_id.is_some_and(|s| Some(s) == self.sch)
    }

    pub fn expired(&self, now: u64) -> bool {
        self.exp <= now
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const KEY: &str = "0123456789abcdef0123456789abcdef";

    // Generated by Laravel ProctorService::token(7, 5, [9]) with KEY. exp is 600s after issue.
    const LARAVEL_TOKEN: &str = "eyJzdWIiOjcsImV4cCI6MTc5NTIzMTUxMSwiYXR0Ijo1LCJhc20iOls5XX0.d169807e876d8ff67700dd3c5179969604349e7c221d1b502c2ee726c8444e0f";

    fn sign(key: &str, claims: &str) -> String {
        let payload = URL_SAFE_NO_PAD.encode(claims);
        let mut mac = HmacSha256::new_from_slice(key.as_bytes()).unwrap();
        mac.update(payload.as_bytes());
        let sig: String = mac.finalize().into_bytes().iter().map(|b| format!("{b:02x}")).collect();
        format!("{payload}.{sig}")
    }

    #[test]
    fn accepts_a_valid_token_and_reads_scope() {
        let secret = Secret::new(KEY).unwrap();
        let token = sign(KEY, r#"{"sub":7,"exp":4102444800,"att":5,"asm":[9]}"#);
        let claims = secret.verify(&token, 1_000).unwrap();
        assert_eq!(claims.sub, 7);
        assert!(claims.covers(Some(5), None, None, None, false));
        assert!(claims.covers(None, Some(9), None, None, false));
        assert!(!claims.covers(Some(6), Some(8), None, None, false));
    }

    #[test]
    fn waiting_student_token_only_gets_their_own_user_events() {
        let secret = Secret::new(KEY).unwrap();
        let token = sign(KEY, r#"{"sub":7,"exp":4102444800}"#);
        let claims = secret.verify(&token, 1_000).unwrap();
        assert!(claims.covers(None, None, Some(7), None, false));
        assert!(!claims.covers(None, None, Some(8), None, false));
        assert!(!claims.covers(Some(5), Some(9), None, None, false));
    }

    #[test]
    fn student_gets_exam_control_only_for_their_own_exam() {
        let secret = Secret::new(KEY).unwrap();
        let token = sign(KEY, r#"{"sub":7,"exp":4102444800,"att":5,"ass":9}"#);
        let claims = secret.verify(&token, 1_000).unwrap();
        assert!(claims.covers(None, Some(9), None, None, true), "pause/resume/stop of own exam");
        assert!(!claims.covers(None, Some(9), None, None, false), "other assessment-wide events stay teacher-only");
        assert!(!claims.covers(None, Some(8), None, None, true), "another exam's control event");
        assert!(!claims.covers(None, None, None, None, true));
    }

    #[test]
    fn teacher_sees_their_whole_school_including_exams_created_later() {
        let secret = Secret::new(KEY).unwrap();
        let token = sign(KEY, r#"{"sub":7,"exp":4102444800,"asm":[1],"sch":3}"#);
        let claims = secret.verify(&token, 1_000).unwrap();
        assert!(claims.covers(None, Some(99), None, Some(3), false), "new exam of the same school");
        assert!(!claims.covers(None, Some(99), None, Some(4), false), "another school");
        assert!(claims.covers(None, None, None, Some(3), false), "school-wide events without an exam id");
    }

    #[test]
    fn accepts_token_signed_by_laravel() {
        let secret = Secret::new(KEY).unwrap();
        let claims = secret.verify(LARAVEL_TOKEN, 1_000).unwrap();
        assert_eq!(claims.sub, 7);
        assert_eq!(claims.att, Some(5));
        assert_eq!(claims.asm, vec![9]);
    }

    #[test]
    fn rejects_bad_signature_expired_and_malformed() {
        let secret = Secret::new(KEY).unwrap();
        let forged = sign("wrong-key-wrong-key-wrong-key-00", r#"{"sub":1,"exp":4102444800}"#);
        assert_eq!(secret.verify(&forged, 1_000), Err(TokenError::BadSignature));

        let expired = sign(KEY, r#"{"sub":1,"exp":500}"#);
        assert_eq!(secret.verify(&expired, 1_000), Err(TokenError::Expired));

        assert_eq!(secret.verify("nodot", 1_000), Err(TokenError::Malformed));
    }

    #[test]
    fn short_secret_is_refused() {
        assert!(Secret::new("too-short").is_none());
    }
}
